"""Build a project's index, then keep it up to date by reprocessing only changed files."""

from __future__ import annotations

import hashlib
import re
import time
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath
from typing import Protocol

import numpy as np

from ..ingest.chunking import DATA_EXTENSIONS, NOTEBOOK_EXTENSIONS, Chunk, Chunker
from ..ingest.graph import FileGraph, GraphExtractor
from ..ingest.profiling import PROFILE_EXTENSIONS, ProfileError, profile_chunks
from ..ingest.walker import SourceFile, walk
from .store import FileRecord, Store

# Bump when what gets stored changes, so existing indexes rebuild on the next learn.
PIPELINE_VERSION = 2

DATA_PREVIEW_BYTES = 64 * 1024
# Notebooks are mostly embedded output images; only their cell sources get indexed.
MAX_NOTEBOOK_BYTES = 25_000_000
MAX_DATA_BYTES = 4_000_000_000


class DocumentEmbedder(Protocol):
    model: str
    batch_size: int

    def embed_documents(self, texts: list[str]) -> np.ndarray: ...


ProgressFn = Callable[[int, int, str], None]


@dataclass
class LearnReport:
    scanned: int = 0
    added: int = 0
    updated: int = 0
    unchanged: int = 0
    removed: int = 0
    skipped: int = 0
    chunks: int = 0
    rebuilt: bool = False
    seconds: float = 0.0
    errors: list[str] = field(default_factory=list)
    missing_grammars: set[str] = field(default_factory=set)

    @property
    def changed(self) -> bool:
        return bool(self.added or self.updated or self.removed or self.rebuilt)


def embedding_text(path: str, chunk: Chunk) -> str:
    header = f"{path} | {', '.join(chunk.symbols[:8])}" if chunk.symbols else path
    return f"{header}\n{chunk.text}"


def index_signature(embed_model: str, chunk_chars: int) -> str:
    return f"{embed_model}|{chunk_chars}|v{PIPELINE_VERSION}"


def _read(f: SourceFile, max_file_bytes: int) -> tuple[bytes, str | None]:
    """Return (content, skip reason)."""
    ext = PurePosixPath(f.rel).suffix.lower()
    limit = MAX_NOTEBOOK_BYTES if ext in NOTEBOOK_EXTENSIONS else max_file_bytes
    if f.size > limit:
        return b"", f"larger than {limit // 1000:,} KB"
    with open(f.path, "rb") as fh:
        data = fh.read()
    if b"\x00" in data[:8192]:
        return data, "binary"
    return data, None


_GENERATOR = re.compile(rb"""<meta\s+name=["']generator["']\s+content=["']([^"']+)["']""", re.IGNORECASE)
_DOC_GENERATORS = ("pdoc", "sphinx", "docutils", "doxygen", "javadoc", "typedoc", "jsdoc", "mkdocs", "rustdoc", "docfx")


def _generated_docs(data: bytes) -> str | None:
    """Name the tool if this HTML page is generated API documentation. Its source is
    indexed already, and the copies would crowd it out of search results."""
    head = data[:20_000]
    match = _GENERATOR.search(head)
    generator = match.group(1).decode("ascii", "replace") if match else ""
    if not generator and b"Generated by javadoc" in head:
        generator = "javadoc"
    if generator and any(tool in generator.lower() for tool in _DOC_GENERATORS):
        return generator.split()[0]
    return None


def _sha1_file(f: SourceFile) -> str:
    digest = hashlib.sha1()
    with open(f.path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def _decode(data: bytes) -> str:
    try:
        return data.decode("utf-8-sig")
    except UnicodeDecodeError:
        return data.decode("cp1252", errors="replace")


def learn(
    root: Path,
    store: Store,
    embedder: DocumentEmbedder,
    *,
    max_file_bytes: int = 1_000_000,
    chunk_chars: int = 2400,
    full: bool = False,
    progress: ProgressFn | None = None,
) -> LearnReport:
    started = time.perf_counter()
    report = LearnReport()

    signature = index_signature(embedder.model, chunk_chars)
    if full or store.get_meta("signature") != signature:
        report.rebuilt = bool(store.files())
        store.clear()
        store.set_meta("signature", signature)

    known = store.files()
    files = list(walk(root))
    report.scanned = len(files)
    seen = {f.rel for f in files}
    for path in sorted(set(known) - seen):
        store.delete_file(path)
        report.removed += 1

    todo = []
    for f in files:
        rec = known.get(f.rel)
        if rec is not None and rec.size == f.size and rec.mtime == f.mtime:
            report.unchanged += 1
        else:
            todo.append(f)

    chunker = Chunker(chunk_chars)
    extractor = GraphExtractor(chunker._parser)
    pending: list[tuple[FileRecord, list[Chunk], FileGraph | None, bool]] = []
    pending_chunks = 0

    def flush() -> None:
        nonlocal pending, pending_chunks
        texts = [embedding_text(rec.path, c) for rec, chunks, _, _ in pending for c in chunks]
        vectors = embedder.embed_documents(texts)
        offset = 0
        for rec, chunks, graph, is_new in pending:
            store.put_file(rec, chunks, vectors[offset : offset + len(chunks)], graph)
            offset += len(chunks)
            report.chunks += len(chunks)
            if is_new:
                report.added += 1
            else:
                report.updated += 1
        pending, pending_chunks = [], 0

    def record(f: SourceFile, sha: str, status: str, n_chunks: int = 0) -> FileRecord:
        return FileRecord(f.rel, f.size, f.mtime, sha, status, n_chunks)

    for done, f in enumerate(todo):
        if progress:
            progress(done, len(todo), f.rel)
        prev = known.get(f.rel)
        ext = PurePosixPath(f.rel).suffix.lower()
        graph: FileGraph | None = None
        try:
            if ext in PROFILE_EXTENSIONS:
                if f.size > MAX_DATA_BYTES:
                    data, reason = b"", f"larger than {MAX_DATA_BYTES // 1_000_000:,} MB"
                    sha = f"size:{f.size}"
                else:
                    data, reason = b"", None
                    sha = _sha1_file(f)
            else:
                data, reason = _read(f, max_file_bytes)
                sha = hashlib.sha1(data).hexdigest()
                if reason is None and ext in (".html", ".htm"):
                    generator = _generated_docs(data)
                    reason = f"generated API docs ({generator})" if generator else None
        except OSError as exc:
            report.errors.append(f"{f.rel}: {exc}")
            continue
        if prev is not None and prev.sha1 == sha:
            store.touch_file(f.rel, f.size, f.mtime)
            report.unchanged += 1
            continue
        if reason:
            store.put_file(record(f, sha, f"skipped: {reason}"))
            report.skipped += 1
            continue
        try:
            if ext in PROFILE_EXTENSIONS:
                chunks = _profile(f, ext, chunker)
            else:
                text = _decode(data)
                chunks = chunker.chunk(f.rel, text)
                graph = extractor.extract(f.rel, text)
        except ProfileError as exc:
            store.put_file(record(f, sha, f"skipped: {exc}"))
            report.skipped += 1
            continue
        except Exception as exc:  # one unparseable file must not stop the whole run
            report.errors.append(f"{f.rel}: {type(exc).__name__}: {exc}")
            store.put_file(record(f, sha, f"error: {type(exc).__name__}"))
            continue
        if not chunks:
            store.put_file(record(f, sha, "empty"))
            report.skipped += 1
            continue
        pending.append((record(f, sha, "indexed", len(chunks)), chunks, graph, prev is None))
        pending_chunks += len(chunks)
        if pending_chunks >= embedder.batch_size * 4:
            flush()

    if pending:
        flush()
    if report.changed:
        store.relink_imports()
    if progress:
        progress(len(todo), len(todo), "")

    store.set_meta("last_learn", str(time.time()))
    report.missing_grammars = chunker.missing_grammars
    report.seconds = time.perf_counter() - started
    return report


def _profile(f: SourceFile, ext: str, chunker: Chunker) -> list[Chunk]:
    try:
        return profile_chunks(f.rel, f.path, chunker.max_chars)
    except ProfileError:
        if ext not in DATA_EXTENSIONS:
            raise
    # CSV/TSV that DuckDB can't read: fall back to a plain preview of the first rows.
    with open(f.path, "rb") as fh:
        head = fh.read(DATA_PREVIEW_BYTES)
    if b"\x00" in head[:8192]:
        raise ProfileError("binary")
    return chunker.chunk(f.rel, _decode(head))
